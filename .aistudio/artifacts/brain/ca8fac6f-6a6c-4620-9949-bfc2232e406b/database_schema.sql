alter table cctv_device_preferences enable row level security;
alter table cctv_streams enable row level security;
alter table cctv_motion_alerts enable row level security;
alter table cctv_commands enable row level security;
alter table cctv_paired_devices enable row level security;
alter table cctv_fcm_tokens enable row level security;

