-- 1. Device Preferences (Remember Role / Auto-Open / Reboot Persistence)
-- Stores each phone's configured feature (CAMERA_SENDER vs VIEWER_MONITOR)
create table if not exists cctv_device_preferences (
    device_id text primary key,
    username text not null,
    selected_mode text not null default 'CAMERA_SENDER', -- 'CAMERA_SENDER' or 'VIEWER_MONITOR'
    remember_choice boolean default true,
    auto_start_on_boot boolean default true,
    device_model text,
    updated_at bigint default (extract(epoch from now()) * 1000)::bigint
);

-- 2. Active CCTV Streams (Camera Status & Realtime Sync)
create table if not exists cctv_streams (
    username text primary key,
    is_live boolean default true,
    torch_on boolean default false,
    lens_facing_front boolean default false,
    siren_active boolean default false,
    night_vision boolean default false,
    battery_level integer default 100,
    recording_active boolean default false,
    frame_base64 text,
    updated_at bigint default (extract(epoch from now()) * 1000)::bigint
);

-- 3. Motion Alerts & Snapshots
create table if not exists cctv_motion_alerts (
    id bigint generated by default as identity primary key,
    username text not null,
    device_id text not null,
    device_name text not null,
    severity text not null,
    intensity float not null,
    description text,
    snapshot_base64 text,
    torch_triggered boolean default false,
    acknowledged boolean default false,
    timestamp bigint default (extract(epoch from now()) * 1000)::bigint
);

-- 4. Remote Control Commands (Viewer -> Camera)
create table if not exists cctv_commands (
    id bigint generated by default as identity primary key,
    device_id text not null,
    username text not null,
    action text not null,
    consumed boolean default false,
    timestamp bigint default (extract(epoch from now()) * 1000)::bigint
);

-- 5. Paired CCTV Devices
create table if not exists cctv_paired_devices (
    id bigint generated by default as identity primary key,
    username text not null,
    pairing_code text not null unique,
    device_name text not null,
    ip_address text,
    created_at bigint default (extract(epoch from now()) * 1000)::bigint
);

-- 6. FCM Push Notification Tokens
create table if not exists cctv_fcm_tokens (
    fcm_token text primary key,
    username text not null,
    device_label text,
    is_viewer boolean default true,
    last_seen bigint default (extract(epoch from now()) * 1000)::bigint
);

-- ============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- Ensures instant access for authenticated and anonymous API client tokens
