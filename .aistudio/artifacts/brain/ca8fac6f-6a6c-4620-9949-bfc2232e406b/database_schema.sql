drop policy if exists "Allow all on cctv_device_preferences" on cctv_device_preferences;
create policy "Allow all on cctv_device_preferences" on cctv_device_preferences for all using (true) with check (true);

drop policy if exists "Allow all on cctv_streams" on cctv_streams;
create policy "Allow all on cctv_streams" on cctv_streams for all using (true) with check (true);

drop policy if exists "Allow all on cctv_motion_alerts" on cctv_motion_alerts;
create policy "Allow all on cctv_motion_alerts" on cctv_motion_alerts for all using (true) with check (true);

drop policy if exists "Allow all on cctv_commands" on cctv_commands;
create policy "Allow all on cctv_commands" on cctv_commands for all using (true) with check (true);

drop policy if exists "Allow all on cctv_paired_devices" on cctv_paired_devices;
create policy "Allow all on cctv_paired_devices" on cctv_paired_devices for all using (true) with check (true);

